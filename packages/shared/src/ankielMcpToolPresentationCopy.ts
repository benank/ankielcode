/** @public */
export function resolveAnkielMcpToolPresentation(
  toolName: string | null | undefined,
  input?: unknown,
  resolve: MFunctionType = mFallback,
): AnkielMcpToolPresentation | null {
  const definition = resolveAnkielMcpToolDefinition(toolName, input);
  if (definition === null) return null;
  const displayName = DISPLAY_NAMES.get(definition.displayName);
  return {
    displayName: displayName === undefined ? definition.displayName : resolve(displayName),
    logo: "ankiel-code",
  };
}
