#!/usr/bin/env node
// Writes AnkielCode/DesignSystem/ThemePalettes.generated.swift from the RN app's theme variables
// (apps/mobile/src/lib/mobileTheme.ts, which reads packages/shared/src/themePalettes.ts), so the
// native palettes are RN's exact sRGB values: OKLCH converted, muted text contrast-corrected.
//
//   node apps/ios/scripts/generate-theme-palettes.mjs          # regenerate
//   node apps/ios/scripts/generate-theme-palettes.mjs --check  # fail if the file is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../../..");
const output = join(here, "../AnkielCode/DesignSystem/ThemePalettes.generated.swift");

const mobile = await import(join(repo, "apps/mobile/src/lib/mobileTheme.ts"));
const { getMobileThemeVariables, getMobileThemeColors, getMobileThemePreviewColors, MOBILE_THEME_OPTIONS } =
  mobile;

/** Native role ← RN variable (or `raw:<role>` for a theme color RN's variables do not expose). */
const ROLES = {
  canvas: "--color-screen",
  sheet: "--color-sheet-solid",
  surface: "--color-card",
  surfaceRaised: "--color-card-alt",
  groupedRow: "--color-grouped-card",
  fill: "--color-subtle",
  fillStrong: "--color-subtle-strong",
  border: "--color-border",
  separator: "--color-separator",
  inputBorder: "--color-input-border",
  sidebar: "--color-drawer",
  textPrimary: "--color-foreground",
  textSecondary: "--color-foreground-secondary",
  textTertiary: "--color-foreground-muted",
  placeholder: "--color-placeholder",
  accent: "--color-primary",
  onAccent: "--color-primary-foreground",
  accentText: "--color-primary-text",
  link: "--color-md-link",
  focus: "--color-focus",
  primaryButton: "--color-prominent-action",
  onPrimaryButton: "--color-prominent-action-foreground",
  signalActive: "--color-signal-active",
  signalSuccess: "--color-signal-success",
  warning: "--color-warning-foreground",
  warningSurface: "--color-warning",
  danger: "--color-danger-foreground",
  dangerSurface: "--color-danger",
  userBubble: "--color-user-bubble",
  userBubbleText: "--color-user-bubble-foreground",
  codeBackground: "--color-md-code-bg",
  codeText: "--color-md-code-text",
  quoteBar: "--color-md-blockquote-border",
  switchTrack: "--color-switch-active-track",
  terminalBackground: "raw:terminalBackground",
  terminalForeground: "raw:terminalForeground",
  terminalCursor: "raw:terminalCursor",
  terminalSelection: "raw:terminalSelection",
};

const themes = MOBILE_THEME_OPTIONS.filter((option) => option.id !== "material-you");

function rgba(value) {
  const hex = /^#([\da-f]{6})$/i.exec(value);
  if (hex) return `0x${hex[1].toUpperCase()}FF`;
  const fn = /^rgba?\(\s*(\d+)[,\s]+(\d+)[,\s]+(\d+)(?:[,\s/]+([\d.]+))?\s*\)$/i.exec(value);
  if (!fn) throw new Error(`unsupported color ${value}`);
  const alpha = Math.round((fn[4] === undefined ? 1 : Number(fn[4])) * 255);
  return `0x${[fn[1], fn[2], fn[3], alpha].map((c) => Number(c).toString(16).padStart(2, "0").toUpperCase()).join("")}`;
}

function palette(id, appearance) {
  const variables = getMobileThemeVariables(id, appearance);
  const raw = getMobileThemeColors(id, appearance);
  const nativeRaw = (role) => mobile.themeColorToNativeColor(raw[role]);
  const fields = Object.entries(ROLES).map(([role, source]) => {
    const value = source.startsWith("raw:") ? nativeRaw(source.slice(4)) : variables[source];
    if (value === undefined) throw new Error(`${id} ${appearance}: no ${source}`);
    return `${role}: ${rgba(value)}`;
  });
  const preview = getMobileThemePreviewColors(id, appearance);
  fields.push(
    `previewAccent: ${rgba(mobile.themeColorToNativeColor(preview.accent))}`,
    `previewAction: ${rgba(mobile.themeColorToNativeColor(preview.messageAction))}`,
  );
  return `ThemeColors(\n      ${fields.join(",\n      ")})`;
}

const caseName = (id) => id.replace(/-(\w)/g, (_, letter) => letter.toUpperCase());

const swift = `// Generated by apps/ios/scripts/generate-theme-palettes.mjs from apps/mobile/src/lib/mobileTheme.ts
// and packages/shared/src/themePalettes.ts. Do not edit; rerun the script.

/// A theme's colors for one appearance, as 0xRRGGBBAA sRGB.
nonisolated struct ThemeColors: Sendable {
${Object.keys(ROLES)
  .map((role) => `  let ${role}: UInt32`)
  .join("\n")}
  /// The Appearance settings swatch (RN \`getMobileThemePreviewColors\`).
  let previewAccent: UInt32
  let previewAction: UInt32
}

/// The color themes RN mobile offers on iOS (Material You is Android-only).
nonisolated enum ThemeID: String, Sendable, CaseIterable, Codable {
${themes.map((theme) => `  case ${caseName(theme.id)} = "${theme.id}"`).join("\n")}

  /// The English name (localized at the call site).
  var label: String {
    switch self {
${themes.map((theme) => `    case .${caseName(theme.id)}: "${theme.label}"`).join("\n")}
    }
  }

  func colors(dark: Bool) -> ThemeColors {
    switch (self, dark) {
${themes
  .flatMap((theme) =>
    ["light", "dark"].map(
      (appearance) =>
        `    case (.${caseName(theme.id)}, ${appearance === "dark"}): Self.${caseName(theme.id)}${appearance === "dark" ? "Dark" : "Light"}`,
    ),
  )
  .join("\n")}
    }
  }

${themes
  .flatMap((theme) =>
    ["light", "dark"].map(
      (appearance) =>
        `  private static let ${caseName(theme.id)}${appearance === "dark" ? "Dark" : "Light"} = ${palette(theme.id, appearance)}`,
    ),
  )
  .join("\n\n")}
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(output, "utf8");
  } catch {}
  if (current !== swift) {
    console.error(
      "ThemePalettes.generated.swift is out of date with themePalettes.ts / mobileTheme.ts.\nRun: node apps/ios/scripts/generate-theme-palettes.mjs",
    );
    process.exit(1);
  }
  console.log("ThemePalettes.generated.swift is up to date.");
} else {
  writeFileSync(output, swift);
  console.log(`Wrote ${output}`);
}
