import {
  ANKIEL_CODE_DARK_THEME_COLORS,
  ANKIEL_CODE_LIGHT_THEME_COLORS,
  SIGNAL_COLORS,
  THEME_COLOR_ROLES,
  THEME_CSS_VARIABLES,
  type ThemeAppearance,
} from "@ankielcode/shared/themePalettes";

export const DEFAULT_THEME_CSS_FILE = "generated-default-theme.css";

function declarations(appearance: ThemeAppearance, indent: string): string[] {
  const colors =
    appearance === "light" ? ANKIEL_CODE_LIGHT_THEME_COLORS : ANKIEL_CODE_DARK_THEME_COLORS;
  return [
    ...THEME_COLOR_ROLES.map((role) => `${indent}${THEME_CSS_VARIABLES[role]}: ${colors[role]};`),
    `${indent}--signal-active: ${SIGNAL_COLORS.active[appearance]};`,
    `${indent}--signal-success: ${SIGNAL_COLORS.success[appearance]};`,
  ];
}

/** The default theme's role variables, from the palette mobile and the server also read. */
export function renderDefaultThemeCSS(): string {
  return [
    `/* Generated by scripts/generate-default-theme.ts from packages/shared/src/themePalettes.ts. Do not edit manually. */`,
    ":root {",
    ...declarations("light", "  "),
    "",
    "  @variant dark {",
    ...declarations("dark", "    "),
    "  }",
    "}",
    "",
  ].join("\n");
}
